// 金額入力（よく使う金額＋テンキー）のテスト
const { chromium, devices } = require('/opt/node-tools/node_modules/playwright');
const ok = (c, m) => { console.log((c ? 'OK  ' : 'NG  ') + m); if (!c) process.exitCode = 1; };
(async () => {
  const b = await chromium.launch();
  const c = await b.newContext({ ...devices['iPhone 13'], viewport: { width: 390, height: 844 } }); await require('./fontroute.js')(c);
  await c.addInitScript(() => Object.defineProperty(navigator, 'standalone', { get: () => true }));
  const p = await c.newPage();
  p.on('pageerror', e => ok(false, 'pageerror ' + e.message));
  await p.goto('http://localhost:8765/');
  await p.evaluate(() => localStorage.setItem('nokori:hideInstallTip', 'true'));
  await p.fill('[data-name]', '自分'); await p.fill('[data-bal]', '100000'); await p.click('[data-start]'); await p.click('[data-ob-next]'); await p.click('[data-ob-next]'); await p.waitForTimeout(400); await p.click('.sheet [data-later]');
  await p.waitForTimeout(600);
  const amt = () => p.evaluate(() => padAmount());
  const key = async ks => { for (const k of ks) await p.click(`[data-act="pad-key"][data-k="${k}"]`); };
  const q = v => p.click(`[data-act="pad-quick"][data-v="${v}"]`);
  const back = () => p.click('[data-act="pad-back"]');
  ok(await p.$$eval('.pad-quick button', b => b.map(x => x.textContent).join(',')) === '500,1,000,1,500,2,000,3,000', 'よく使う金額の初期値');
  ok(await p.$eval('.pad-cats button', b => b.disabled), '金額0ではカテゴリ押せない');
  await q(1500); ok(await amt() === 1500, 'ワンタップで1,500');
  ok(await p.$eval('.pad-quick button.on', b => b.textContent) === '1,500', '押した金額が光る');
  ok(await p.$eval('.pad-hint', e => e.classList.contains('on')), '「タップで登録」が目立つ');
  await key(['8']); ok(await amt() === 8, 'ワンタップ直後の数字は打ち直し');
  ok(!(await p.$('.pad-quick button.on')), '打ち直したら光が消える');
  await q(1500); await back(); await back(); await key(['8', '0']); ok(await amt() === 1580, '1,500 → ⌫⌫ → 80 で 1,580');
  await p.click('[data-act="pad-clear"]'); ok(await amt() === 0, '×で全部消す');
  await key(['0', '00']); ok(await amt() === 0, '先頭の0は無視');
  await key(['1', '2', '8', '0']); ok(await amt() === 1280, 'テンキーで1,280');
  await back(); ok(await amt() === 128, '⌫で1文字消える');
  await key(['0']); await key(['00', '00', '00']); ok(await amt() === 128000, '桁あふれは入らない（' + await amt() + '）');
  await p.click('[data-act="pad-clear"]');
  await key(['1', '2', '8', '0']); await p.click('[data-act="pad-cat"][data-cat="conv"]');
  ok(await p.evaluate(() => D.tx.some(x => x.amount === 1280 && x.cat === 'conv')), '1,280円をコンビニで登録');
  ok(await p.evaluate(() => balance()) === 98720, '残高が減る');
  ok(await amt() === 0, '登録後は0に戻る');
  await q(500); await p.click('[data-act="pad-plain"]'); ok(await p.evaluate(() => balance()) === 98220, 'そのまま登録');
  await key(['3', '8', '00']); await p.click('[data-act="pad-memo"]');
  ok(await p.$eval('.sheet', s => !!s), 'メモを付けて登録のシートが開く');
  await p.fill('.sheet [data-memo]', '美容院'); await p.click('.sheet [data-cat="beauty"]');
  ok(await p.evaluate(() => D.tx.some(x => x.amount === 3800 && x.memo === '美容院')), 'メモ付きで3,800');
  // スクロールなしで全部見えるか（iPhone 13）
  await p.evaluate(() => scrollTo(0, 0)); await p.waitForTimeout(5500);
  const last = await p.$eval('.pad-cats button:last-child', e => e.getBoundingClientRect().bottom);
  const tab = await p.$eval('#tabbar', e => e.getBoundingClientRect().top);
  ok(last < tab, `カテゴリがスクロールなしで見える（${Math.round(last)} < ${Math.round(tab)}）`);
  await p.screenshot({ path: process.argv[2] + '/k0.png' });
  // 設定で変える
  await p.click('#tabbar [data-view="settings"]');
  await p.evaluate(() => { D.mode = 'pro'; save(); render(); }); await p.click('.menu [data-act="quick-set"]');
  const ins = await p.$$('.sheet [data-q]');
  await ins[0].fill('300'); await ins[1].fill('800'); await ins[4].fill('5000');
  await p.screenshot({ path: process.argv[2] + '/k1.png' });
  await ins[2].fill(''); await p.click('.sheet [data-save]');
  ok(await p.$('.sheet') !== null, '空欄では保存できない');
  await ins[2].fill('1,200'); await p.click('.sheet [data-save]');
  ok(await p.evaluate(() => D.quick.join(',')) === '300,800,1200,2000,5000', '保存して並び替え');
  await p.reload(); await p.waitForTimeout(800);
  if (await p.$('[data-act="pad-quick"]') === null) await p.click('#tabbar [data-view="home"]');
  ok(await p.$$eval('.pad-quick button', b => b.map(x => x.textContent).join(',')) === '300,800,1,200,2,000,5,000', '開き直しても残る');
  await q(800); ok(await amt() === 800, '変えた金額でワンタップ');
  await p.screenshot({ path: process.argv[2] + '/k2.png' });
  await b.close();
})();
